"""
Experiment Reporter — generates A/B experiment reports.

Usage::

    from evaluation.ab_testing import ABTestManager
    from evaluation.experiment_reporter import ExperimentReporter

    ab = ABTestManager(dry_run=True)
    result = ab.run_experiment("resume", "v1.0", "v1.0")
    ExperimentReporter().write_markdown(result, "evaluation/reports/experiment.md")
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict

from evaluation.ab_testing import ABResult


def _ts() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _ensure_parent(path: str | Path) -> Path:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    return p


class ExperimentReporter:
    """Generate JSON and Markdown reports for A/B experiments."""

    def write_json(self, result: ABResult, path: str | Path) -> Path:
        out = _ensure_parent(path)
        report = {
            "generated_at": _ts(),
            "experiment": result.to_dict(),
        }
        with open(out, "w", encoding="utf-8") as fh:
            json.dump(report, fh, indent=2, ensure_ascii=False)
        return out

    def write_markdown(self, result: ABResult, path: str | Path) -> Path:
        out = _ensure_parent(path)
        lines: list[str] = []
        _a = lines.append

        _a(f"# A/B Experiment Report\n")
        _a(f"*Generated: {_ts()}*\n")

        _a("## Configuration\n")
        _a(f"| Setting | Value |")
        _a(f"|---------|-------|")
        _a(f"| Agent | {result.agent} |")
        _a(f"| Version A | {result.version_a} |")
        _a(f"| Version B | {result.version_b} |")
        _a(f"| Test cases | {result.test_cases} |")
        _a(f"| Duration | {result.duration_seconds:.1f}s |")
        _a("")

        # Scores
        avg_a = sum(result.scores_a) / max(len(result.scores_a), 1)
        avg_b = sum(result.scores_b) / max(len(result.scores_b), 1)
        _a("## Results\n")
        _a(f"| Metric | Version A | Version B |")
        _a(f"|--------|-----------|-----------|")
        _a(f"| Avg Score | {avg_a:.3f} | {avg_b:.3f} |")
        _a(f"| Test Cases | {len(result.scores_a)} | {len(result.scores_b)} |")
        _a("")

        # Statistics
        if result.stats:
            s = result.stats
            _a("## Statistical Analysis\n")
            _a(f"| Statistic | Value |")
            _a(f"|-----------|-------|")
            _a(f"| Mean difference (B - A) | {s.mean_diff:.4f} |")
            _a(f"| t-statistic | {s.t_statistic:.4f} |")
            _a(f"| p-value | {s.p_value:.6f} |")
            _a(f"| 95% CI | [{s.ci_lower:.4f}, {s.ci_upper:.4f}] |")
            _a(f"| Cohen's d | {s.effect_size:.4f} |")
            _a(f"| Significant | {'Yes' if s.significant else 'No'} |")
            _a("")

        # Winner
        _a("## Conclusion\n")
        if result.winner:
            _a(f"**Winner: Version {result.winner}** "
               f"({result.version_a if result.winner == 'A' else result.version_b})\n")
        else:
            _a("**No statistically significant difference** between the two versions.\n")

        _a("---")
        _a("*Report generated by AI Job Application Coach A/B Testing Framework*\n")

        with open(out, "w", encoding="utf-8") as fh:
            fh.write("\n".join(lines))
        return out
